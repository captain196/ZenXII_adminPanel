                               (s.maxMarks ? ' / ' + esc(String(s.maxMarks)) : '') + '</td>' +
                             '<td>' + pct(s.percentage) + '</td>' +
                             '<td>' + esc(s.grade || '—') + '</td>' +
                             '<td>' + (s.passFail ? esc(s.passFail) : '—') + '</td></tr>';
                  }).join('') + '</tbody></table></div>';
            }

            // All exams, so a trend is visible without leaving the page.
            var all = '';
            if (d.exams.length > 1) {
                all = '<h4 style="margin:16px 0 8px;font-size:13.5px">All examinations</h4>' +
                  '<div class="s360-scroll"><table class="s360-table"><thead><tr>' +
                  '<th>Exam</th><th>Marks</th><th>%</th><th>Grade</th><th>Rank</th><th>Result</th></tr></thead><tbody>' +
                  d.exams.map(function (e) {
                      return '<tr><td>' + esc(e.examName || e.examId) + '</td>' +
                             '<td>' + esc(String(e.totalMarks === null ? '—' : e.totalMarks)) +
                               (e.maxMarks ? ' / ' + esc(String(e.maxMarks)) : '') + '</td>' +
                             '<td>' + pct(e.percentage) + '</td>' +
                             '<td>' + esc(e.grade || '—') + '</td>' +
                             '<td>' + (e.rank ? esc(String(e.rank)) : '—') + '</td>' +
                             '<td>' + (e.passFail ? esc(e.passFail) : '—') + '</td></tr>';
                  }).join('') + '</tbody></table></div>';
            }

            var note = '<p class="s360-note">Published results only — drafts in the exam workspace are not shown. ' +
                       'Marks, grades and ranks are computed by the Result module' +
                       (L.gradingScale ? ' (' + esc(L.gradingScale) + ' scale)' : '') + '.</p>';
            return head + subj + all + note;
        },

        // A-3 — Receipt history.
        receipts: function (d) {
            if (!d.available) return '<p class="s360-empty">Payment history is unavailable.</p>';
            if (!d.receipts || !d.receipts.length) return empty('No payments recorded for this student.');

            var rows = d.receipts.map(function (r) {
                return '<tr>' +
                    '<td>' + esc(r.receiptNo || '—') + '</td>' +
                    '<td>' + esc(String(r.date || '').substring(0, 10)) + '</td>' +
                    '<td>' + money(r.amount) + '</td>' +
                    '<td>' + esc(r.paymentMode || '—') + '</td>' +
                    '<td>' + esc(r.collectedBy || '—') + '</td>' +
                    '<td>' + '<span class="s360-chip ' +
                        (String(r.status || 'paid').toLowerCase() === 'cancelled' ? 'off' : 'ok') + '">' +
                        esc(r.status || 'paid') + '</span></td>' +
                    '<td>' + (r.receiptNo
                        ? '<a class="s360-btn" target="_blank" rel="noopener" href="' +
                          esc(BASE + 'fees/student_ledger?uid=' + encodeURIComponent(STUDENT_ID)) + '">View</a>'
                        : '—') + '</td>' +
                    '</tr>';
            }).join('');

            return '<div class="s360-stats" style="margin-top:0">' +
                   '<div class="s360-stat"><div class="k">Receipts</div><div class="v">' + d.receipts.length + '</div></div>' +
                   '<div class="s360-stat"><div class="k">Total collected</div><div class="v">' + money(d.totalPaid) + '</div></div>' +
                   '</div>' +
                   '<div class="s360-scroll"><table class="s360-table"><thead><tr>' +
                   '<th>Receipt No</th><th>Date</th><th>Amount</th><th>Mode</th><th>Collected by</th>' +
                   '<th>Status</th><th></th></tr></thead><tbody>' + rows + '</tbody></table></div>' +
                   (d.truncated ? '<p class="s360-note">Only the most recent receipts are shown.</p>' : '') +
                   '<p class="s360-note">Receipts are issued by the Fees module — this panel is read-only.</p>';
        }
    };

    // Actions whose work is completed in a panel focus that panel instead of
    // navigating — both in the global rail and in the zone strips. Driven by
    // the descriptor's declared `target`/`panel`, so this loop knows nothing
    // about which module or zone an action belongs to.
    document.querySelectorAll('[data-s360-panel]').forEach(function (btn) {
        btn.addEventListener('click', function () {
            revealPanel(btn.getAttribute('data-s360-panel'));
        });
    });

    // E-1 — an alert jumps to the panel that explains it, expanding whichever
    // zone owns that panel. Noticing a problem and inspecting it stays one
    // click even though the panel now lives one level deeper.
    document.querySelectorAll('.s360-alert[data-goto]').forEach(function (a) {
        a.addEventListener('click', function (e) {
            e.preventDefault();
            revealPanel(a.getAttribute('data-goto'));   // no-op if the panel is absent
        });
    });

    // Mount the shared entitlement capture component against this student.
    // Same call the three admission pathways make — no Student-360 variant.
    if (window.ENTCAP) {
        ENTCAP.mount({
            studentId: STUDENT_ID,
            klass:     <?= json_encode((string) ($ctx['className'] ?? ''), JSON_UNESCAPED_UNICODE) ?>,
            section:   <?= json_encode((string) ($ctx['section']   ?? ''), JSON_UNESCAPED_UNICODE) ?>
        });
    }

    // ── Approvals ────────────────────────────────────────────────────────
    // UI over the canonical Phase E endpoints. It decides nothing: it lists
    // what the server returns and posts the operator's choice back.
    function token() {
        var el = document.querySelector('input[name="' + CSRF_NAME + '"]');
        return el ? el.value : '';
    }
    function post(path, fields) {
        var fd = new FormData();
        Object.keys(fields).forEach(function (k) { fd.append(k, fields[k]); });
        fd.append(CSRF_NAME, token());
        return fetch(BASE + path, { method: 'POST', body: fd, credentials: 'same-origin' })
            .then(function (r) {
                return r.json()
                    .then(function (j) { return { httpOk: r.ok, body: j }; })
                    .catch(function ()  { return { httpOk: false, body: null }; });
            })
            .then(function (res) {
                // Phantom-success guard: fetch() does not reject on 403/500,
                // so a denied action would otherwise render as done. Check the
                // HTTP status AND the envelope. Fail closed.
                if (res.body && res.body.csrf_token) {
                    document.querySelectorAll('input[name="' + CSRF_NAME + '"]')
                            .forEach(function (el) { el.value = res.body.csrf_token; });
                }
                if (!res.httpOk || !res.body || res.body.status !== 'success') {
                    throw new Error((res.body && res.body.message) || 'Request failed.');
                }
                return res.body;
            });
    }
    function say(text, ok, msgId) {
        var m = document.getElementById(msgId || 's360ApprMsg');
        if (!m) return;
        m.className = 's360-msg ' + (ok ? 'ok' : 'err');
        m.textContent = text;
    }

    // ── Two approval surfaces, ONE implementation ────────────────────────
    // Money → Entitlements decides on any entitlement.
    // Student & Family → Parent Requests decides on the family's own asks.
    //
    // They differ ONLY by which rows they list. Both call the same endpoint,
    // and neither knows anything the other does not — a second copy of this
    // logic is exactly how two surfaces start disagreeing about the same row.
    var APPR = [
        { box: 's360ApprList',    msg: 's360ApprMsg',    wrap: 's360Appr',
          keep: function (e) { return e.status === 'pending_approval' || e.status === 'active'; },
          none: 'Nothing awaiting approval, and no active entitlement to discontinue.' },
        // S360-Z3 (fixed 2026-08-12). This filtered on
        //     e.source === 'parent_request' && e.status === 'pending_approval'
        // which read correctly but failed the requirement it existed to serve.
        // UAT found the box saying "No parent request is awaiting a decision"
        // while a pending entitlement for that very student sat one zone away
        // in Money — because a staff-raised proposal carries source 'manual'.
        //
        // R-5 says the operator must not have to leave Student & Family to
        // decide on something they are looking at. So this now keeps EVERY
        // pending row and labels each with its origin, rather than silently
        // hiding the ones a parent did not raise. The table above still lists
        // parent submissions only — that panel is about the family's asks;
        // this box is about decisions the operator owes.
        { box: 's360ApprReqList', msg: 's360ApprReqMsg', wrap: 's360ApprReq',
          keep: function (e) { return e.status === 'pending_approval'; },
          none: 'Nothing is awaiting a decision for this student.' }
    ];

    function renderApprovals() {
        if (!STUDENT_ID) return;
        var live = APPR.filter(function (c) { return document.getElementById(c.box); });
        if (!live.length) return;

        // One request feeds both surfaces — listing the same rows twice would
        // double the cost for no additional information.
        post('entitlements/for_student', { student_id: STUDENT_ID }).then(function (r) {
            var all = r.entitlements || [];
            live.forEach(function (c) {
                var box  = document.getElementById(c.box);
                var rows = all.filter(c.keep);
                if (!rows.length) {
                    box.className = 's360-empty';
                    box.textContent = c.none;
                    return;
                }
                box.className = '';
                box.innerHTML = rows.map(function (e) {
                    var what = esc(e.concessionType || e.serviceType || e.kind || 'entitlement');
                    var val  = e.valueType === 'fullExempt' ? 'Full exemption'
                             : (e.valueType === 'percent' ? (e.value + '%') : ('₹' + e.value));
                    var id   = esc(e.entitlementId || '');
                    var btns = e.status === 'pending_approval'
                        ? '<button type="button" class="s360-btn approve" data-act="approve" data-id="' + id + '">Approve</button>' +
                          '<button type="button" class="s360-btn reject"  data-act="reject"  data-id="' + id + '">Reject</button>'
                        : '<button type="button" class="s360-btn reject" data-act="discontinue" data-id="' + id + '">Discontinue</button>';
                    // Show WHO raised it. Now that the request box lists every
                    // pending row (S360-Z3), a staff proposal must not be
                    // mistaken for something the family asked for — the two
                    // carry very different weight in a conversation with a parent.
                    var origin = e.source === 'parent_request'
                        ? ' <span class="s360-chip warn">parent request</span>'
                        : (e.source ? ' <span class="s360-chip off">' + esc(e.source) + '</span>' : '');
                    return '<div class="row"><span class="desc"><strong>' + what + '</strong> · ' +
                           esc(val) + ' · ' + esc(String(e.status).replace('_', ' ')) + origin +
                           '</span>' + btns + '</div>';
                }).join('');
            });
        }).catch(function (err) {
            live.forEach(function (c) {
                var box = document.getElementById(c.box);
                box.className = 's360-empty';
                box.textContent = 'Could not load entitlements: ' + err.message;
            });
        });
    }

    // Delegated per surface, so both survive every re-render without rebinding.
    var apprBound = false;
    APPR.forEach(function (c) {
        var wrap = document.getElementById(c.wrap);
        if (!wrap) return;
        apprBound = true;

        wrap.addEventListener('click', function (ev) {
            var btn = ev.target.closest ? ev.target.closest('[data-act]') : null;
            if (!btn) return;
            // NOTE: this handler deliberately does NOT branch on which surface
            // was clicked. It used to (`isReq`), and S360-Z4 records why that
            // was removed — the confirmation now reads the same from Money and
            // from Student & Family, because the fact it states is about the
            // entitlement, not about the button.
            var act = btn.getAttribute('data-act');
            var id  = btn.getAttribute('data-id');
            if (!id) { say('This entitlement has no id and cannot be actioned.', false, c.msg); return; }

            var fields = { entitlement_id: id };
            // reject and discontinue take a reason; approve takes an optional
            // note. A cancelled prompt aborts — it must not post an empty
            // reason and record an unexplained decision.
            if (act === 'reject' || act === 'discontinue') {
                var reason = window.prompt(
                    act === 'reject' ? 'Reason for rejection:' : 'Reason for discontinuing:');
                if (reason === null || !reason.trim()) return;
                fields.reason = reason.trim();
            }

            btn.disabled = true;
            post('entitlements/' + act, fields).then(function (r) {
                // ── S360-Z4 ──────────────────────────────────────────────
                // The destination is now stated UNCONDITIONALLY on approve,
                // rather than only when the click came from the request box.
                //
                // Two reasons. First, empirical: UAT 9.10c showed the
                // surface-conditional wording never appearing even though the
                // DOM proved the button sat inside `#s360ApprReq`
                // (`closest('#s360ApprReq')` returned truthy on the live page).
                // I could not isolate why the flag failed to take, and a
                // confirmation about money is not something to leave resting on
                // a condition I cannot explain.
                //
                // Second, and better: an operator approving from Money →
                // Entitlements benefits from the same sentence. Where the row
                // went is a fact about the row, not about the button that was
                // pressed. Making it unconditional removes a branch AND says
                // more.
                var msg = r.message || 'Done.';
                if (act === 'approve') {
                    msg = 'Approved. The entitlement is now active under Money → Entitlements.';
                } else if (act === 'reject') {
                    msg = 'Request rejected.';
                } else if (act === 'discontinue') {
                    msg = 'Entitlement discontinued.';
                }
                say(msg, true, c.msg);

                // Refresh twice. The first call is usually stale — the write is
                // not yet visible to the read replica, which is exactly what
                // UAT 9.10d caught (row still listed as pending after a
                // successful approve). The second call, after the app's own
                // ~8s response envelope, is the one that corrects it.
                renderApprovals();
                setTimeout(renderApprovals, 4000);

                // Re-read the whole snapshot from the server rather than
                // patching the DOM, so what is displayed is what actually
                // persisted. A partial apply shows as a partial apply.
                fetch(BASE + 'student360/context/' + encodeURIComponent(STUDENT_ID),
                      { credentials: 'same-origin' })
                    .then(function (r2) { return r2.ok ? r2.json() : null; })
                    .then(function (j) {
                        if (!j || j.status !== 'success') return;
                        // A changed action set means the rail is now stale;
                        // say so rather than silently showing old affordances.
                        say(msg + ' Reload to refresh available actions.', true, c.msg);
                    })
                    .catch(function () { /* refresh is advisory; the action already succeeded */ });
            }).catch(function (err) {
                say(err.message, false, c.msg);
            }).then(function () { btn.disabled = false; });
        });
    });
    if (apprBound) renderApprovals();
})();
