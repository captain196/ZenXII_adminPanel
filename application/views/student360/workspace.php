            if (btn) btn.setAttribute('aria-expanded', on ? 'true' : 'false');
        });
        if (!zone) return;
        // Deliberately NOT calling lazyLoad here — see rule 1.
        if (moveFocus) {
            var t = zone.querySelector('.s360-ztab[aria-selected="true"]') ||
                    zone.querySelector('.s360-ztab');
            if (t) t.focus();
        }
    }

