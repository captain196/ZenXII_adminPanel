    // Five zones, exactly one expanded. The rules that matter:
    //
    //   1. EXPANDING A ZONE FETCHES NOTHING. Only selecting an inner tab can
    //      trigger a lazy load. If expansion ever pulled a zone's panels,
    //      opening Money would cost Receipts and opening Records would cost
    //      Documents — silently converting lazy panels into eager ones and
    //      undoing the entire read-budget design.
    //
    //   2. A zone's PRIMARY panel is whichever tab the server rendered
    //      selected — Fees, Results, Discipline, Transport, Profile. It is
    //      never chosen here, so the locked order cannot drift into
    //      alphabetical or DOM order.
    //
    //   3. Focus follows the operator: into the zone on expand, back to the
    //      header on collapse. Without that, keyboard users lose their place
    //      on every interaction.
    var zones = Array.prototype.slice.call(document.querySelectorAll('.s360-zone'));
    var tabs  = Array.prototype.slice.call(document.querySelectorAll('.s360-ztab'));

