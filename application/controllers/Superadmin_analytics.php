    // ─────────────────────────────────────────────────────────────────────
    // PHASE 1F internals — param normalization + per-section export shape
    // ─────────────────────────────────────────────────────────────────────
    private function _normalize_cross_school_params(): array
    {
        $days = (int) ($this->input->get('days', TRUE) ?? 30);
        if (!in_array($days, [7, 30, 90], true)) $days = 30;
        $months = (int) ($this->input->get('months', TRUE) ?? 12);
        if (!in_array($months, [3, 6, 12], true)) $months = 12;
        $metric = (string) ($this->input->get('metric', TRUE) ?? 'activity_volume');
        $allowedMetrics = ['activity_volume', 'student_growth', 'staff_growth',
                           'data_freshness_hours', 'revenue_contribution'];
        if (!in_array($metric, $allowedMetrics, true)) $metric = 'activity_volume';
        $includeTest = (string) ($this->input->get('include_test', TRUE) ?? '0');
        $includeTest = in_array($includeTest, ['1', 'true', 'yes'], true);
        return [$days, $months, $metric, $includeTest];
    }

    private function _build_cross_school_export_section(string $section, array $payload,
                                                          string $metric, int $days, int $months): array
    {
        switch ($section) {
            case 'overview':
                $kpi = is_array($payload['fleet_kpi'] ?? null) ? $payload['fleet_kpi'] : [];
                $headers = ['KPI', 'Value', 'Window', 'Notes'];
                $rows = [
                    ['Total Audit Events',     (int) ($kpi['total_audit_events']  ?? 0), "{$days}d", 'Σ tenantAudit rows in window across in-scope tenants'],
                    ['Avg Activity / Tenant',  (int) ($kpi['avg_activity_tenant'] ?? 0), "{$days}d", 'total_audit_events ÷ in_scope_count'],
                    ['Total Student Δ',        (int) ($kpi['total_student_delta'] ?? 0), '3mo',      'Σ per-tenant growth deltas from analyticsRollups'],
                    ['Stale Tenants',          (int) ($kpi['stale_tenants_count'] ?? 0) . ' / ' . (int) ($kpi['stale_tenants_total'] ?? 0), 'current', '>7 days since statsCache.lastUpdated'],
                    ['Cross-Tenant MRR (avg)', round((float) ($kpi['cross_tenant_mrr'] ?? 0), 2), 'current', 'MRR ÷ active in-scope tenants (INR)'],
                    ['In-Scope Tenants',       (int) ($kpi['in_scope_count']      ?? 0), 'current', 'Excludes test tenants unless include_test=1'],
                ];
                return [$headers, $rows, 'cross_school_overview'];

            case 'leaderboards':
                $headers = ['Direction', 'Rank', 'School ID', 'School Name', 'Plan', 'Metric Value', 'Is Test Tenant'];
                $rows = [];
                foreach ((array) ($payload['leaderboard_top'] ?? []) as $i => $r) {
                    $rows[] = ['TOP', ($i + 1), $r['schoolId'] ?? '', $r['schoolName'] ?? '',
                               $r['planName'] ?? '', self::_metric_value($r, $metric),
                               !empty($r['isTestTenant']) ? 'yes' : 'no'];
                }
                foreach ((array) ($payload['leaderboard_bottom'] ?? []) as $i => $r) {
                    $rows[] = ['BOTTOM', ($i + 1), $r['schoolId'] ?? '', $r['schoolName'] ?? '',
                               $r['planName'] ?? '', self::_metric_value($r, $metric),
                               !empty($r['isTestTenant']) ? 'yes' : 'no'];
                }
                return [$headers, $rows, 'cross_school_leaderboards_' . $metric];

            case 'compare':
            default:
                $headers = ['School ID', 'School Name', 'Code', 'City', 'Plan', 'Lifecycle',
                            'Is Test Tenant', 'Activity ('.$days.'d)', 'Student Δ', 'Staff Δ',
                            'Data Age (h)', 'Revenue (INR/mo)'];
                $rows = [];
                foreach ((array) ($payload['comparative_matrix'] ?? []) as $r) {
                    $rows[] = [
                        (string) ($r['schoolId']             ?? ''),
                        (string) ($r['schoolName']           ?? ''),
                        (string) ($r['schoolCode']           ?? ''),
                        (string) ($r['city']                 ?? ''),
                        (string) ($r['planName']             ?? ''),
                        (string) ($r['lifecycleState']       ?? ''),
                        !empty($r['isTestTenant']) ? 'yes' : 'no',
                        (int)    ($r['activity_volume']      ?? 0),
                        (int)    ($r['student_delta']        ?? 0),
                        (int)    ($r['staff_delta']          ?? 0),
                        $r['data_freshness_hours'] === null ? '—' : (int) $r['data_freshness_hours'],
                        round((float) ($r['revenue_contribution'] ?? 0), 2),
                    ];
                }
                return [$headers, $rows, 'cross_school_compare'];
        }
    }

    private static function _metric_value(array $row, string $metric)
    {
        $v = $row[$metric] ?? null;
        if ($v === null) return '—';
        if (in_array($metric, ['revenue_contribution'], true)) return round((float) $v, 2);
        return is_numeric($v) ? (is_float($v) ? round($v, 2) : (int) $v) : (string) $v;
    }

    // ─────────────────────────────────────────────────────────────────────
    // PHASE 1E internals — per-section export shape
    // ─────────────────────────────────────────────────────────────────────
    private function _build_revenue_export_section(string $section, array $payload, int $monthsBack): array
    {
        $cur = (string) ($payload['currency'] ?? 'INR');
        $kpi = is_array($payload['headline_kpi'] ?? null) ? $payload['headline_kpi'] : [];

        switch ($section) {
            case 'timeseries':
                $headers = ['Period', 'MRR', 'Total Revenue', 'Paid Payments Count'];
                $mrr = is_array($payload['time_series_mrr'] ?? null) ? $payload['time_series_mrr'] : [];
                $pay = is_array($payload['time_series_payments'] ?? null) ? $payload['time_series_payments'] : [];
                // Join by period — both series have identical length and order.
                $rows = [];
                $payByPeriod = [];
                foreach ($pay as $p) $payByPeriod[(string) ($p['period'] ?? '')] = $p;
                foreach ($mrr as $m) {
                    $period = (string) ($m['period'] ?? '');
                    $p = $payByPeriod[$period] ?? [];
                    $rows[] = [
                        $period,
                        (float) ($m['mrr'] ?? 0),
                        (float) ($p['totalRevenue'] ?? 0),
                        (int)   ($p['paidPaymentsCount'] ?? 0),
                    ];
                }
                return [$headers, $rows, 'revenue_timeseries'];

            case 'plans':
                $headers = ['Plan', 'MRR (' . $cur . ')', 'ARR (' . $cur . ')', 'Tenants', 'Avg per Tenant', 'Share %'];
                $rows = [];
                foreach ((array) ($payload['revenue_by_plan'] ?? []) as $p) {
                    $rows[] = [
                        (string) ($p['planName'] ?? ''),
                        round((float) ($p['mrr'] ?? 0), 2),
                        round((float) ($p['arr'] ?? 0), 2),
                        (int)   ($p['tenants'] ?? 0),
                        round((float) ($p['avgPerTenant'] ?? 0), 2),
                        round((float) ($p['sharePct'] ?? 0), 2),
                    ];
                }
                return [$headers, $rows, 'revenue_by_plan'];

            case 'payments':
                $headers = ['Date', 'School ID', 'School Name', 'Plan', 'Amount (' . $cur . ')', 'Method', 'Reference'];
                $rows = [];
                foreach ((array) ($payload['recent_payments'] ?? []) as $p) {
                    $rows[] = [
                        (string) ($p['paidAt']     ?? ''),
                        (string) ($p['schoolId']   ?? ''),
                        (string) ($p['schoolName'] ?? ''),
                        (string) ($p['planName']   ?? ''),
                        round((float) ($p['amount'] ?? 0), 2),
                        (string) ($p['method']     ?? ''),
                        (string) ($p['reference']  ?? ''),
                    ];
                }
                return [$headers, $rows, 'recent_payments'];

            case 'atrisk':
                $headers = ['School ID', 'School Name', 'City', 'Plan', 'State', 'Period End',
                            'Days To/From End', 'At-Risk MRR (' . $cur . ')'];
                $rows = [];
                foreach ((array) ($payload['at_risk_tenants'] ?? []) as $p) {
                    $rows[] = [
                        (string) ($p['schoolId']   ?? ''),
                        (string) ($p['schoolName'] ?? ''),
                        (string) ($p['city']       ?? ''),
                        (string) ($p['planName']   ?? ''),
                        (string) ($p['state']      ?? ''),
                        (string) ($p['periodEnd']  ?? ''),
                        (int)    ($p['daysToEnd']  ?? 0),
                        round((float) ($p['atRiskMrr'] ?? 0), 2),
                    ];
                }
                return [$headers, $rows, 'revenue_at_risk'];

            case 'overview':
            default:
                $headers = ['KPI', 'Value', 'Currency', 'Period', 'Notes'];
                $win = "trailing {$monthsBack} months";
                $rows = [
                    ['MRR',                    round((float) ($kpi['mrr'] ?? 0), 2),                  $cur, 'current',  'Includes trialing per Q-A4'],
                    ['ARR',                    round((float) ($kpi['arr'] ?? 0), 2),                  $cur, 'current',  '= MRR × 12'],
                    ['Total Revenue (window)', round((float) ($kpi['total_revenue_window'] ?? 0), 2), $cur, $win,       'Sum of payments.amount in window'],
                    ['ARPU',                   round((float) ($kpi['arpu'] ?? 0), 2),                 $cur, $win,       'Total revenue ÷ active tenant count'],
                    ['Outstanding Amount',     round((float) ($kpi['outstanding_amount'] ?? 0), 2),   $cur, 'current',  'Σ subscription price (one cycle) for grace+past_due tenants'],
                    ['Outstanding Tenants',    (int) ($kpi['outstanding_count'] ?? 0),                '',   'current',  'Count of tenants in grace/past_due with periodEnd in the past'],
                    ['Active Tenants',         (int) ($kpi['active_tenants'] ?? 0),                   '',   'current',  'Tenants in {active, trialing, expiring_soon, grace}'],
                    ['Total Tenants',          (int) ($kpi['total_tenants'] ?? 0),                    '',   'current',  'All tenants registered in canonical surface'],
                ];
                return [$headers, $rows, 'revenue_overview'];
        }
    }

