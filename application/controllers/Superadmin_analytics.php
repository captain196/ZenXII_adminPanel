/**
 * Superadmin_analytics — Phase 1C+ spoke controller for the Dashboard Hub.
 *
 * Locked design baseline: docs/design/B2_3_4_A_Analytics_Design_Locked.md
 *
 * SPOKES (one route per spoke; controller methods correspond):
 *   /superadmin/dashboard/statistics      (Phase 1C — THIS PHASE)
 *   /superadmin/dashboard/schools-search  (Phase 1D)
 *   /superadmin/dashboard/revenue         (Phase 1E)
 *   /superadmin/dashboard/cross-school    (Phase 1F)
 *   /superadmin/dashboard/tenant/{id}     (Phase 1G)
 *
 * Drill-down URL convention:
 *   /superadmin/dashboard/schools-search?state={...}&plan={...}&city={...}
 *   Generated by Phase 1C charts; consumed by Phase 1D when it ships.
 *
 * URL routing nuance:
 *   The legacy /superadmin/dashboard route is owned by Superadmin::dashboard().
 *   This controller takes /superadmin/dashboard/<spoke> via the existing
 *   CodeIgniter URL pattern of "controller name = first segment". To make
 *   /superadmin/dashboard/statistics dispatch here without adding routes.php
 *   indirection, the route file is extended at Phase 1H. For Phase 1C the
 *   spoke is reachable via the explicit class route /superadmin_analytics/statistics.
 *
 *   The Hub view's spoke navigation buttons + KPI tile links use
 *   /superadmin/dashboard/statistics; for that URL to work today, add the
 *   route alias in application/config/routes.php (Phase 1C scope keeps the
 *   alias localized — see this file's __construct() note).
 */
