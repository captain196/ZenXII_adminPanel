<?php
defined('BASEPATH') or exit('No direct script access allowed');

/**
 * Fee_entitlement_reader — read-only access to `studentEntitlements` for the
 * unified generator. Phase C of the Student Entitlements roadmap. NO writes.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  WHAT THIS IS
 * ─────────────────────────────────────────────────────────────────────────
 *  The successor to Fee_concession_reader. Same job — "which concessions
 *  apply to this demand, and by how much" — but sourced from the unified
 *  `studentEntitlements` log (STUDENT_ENTITLEMENTS_ARCHITECTURE_BASELINE.md
 *  §Data Model) instead of the legacy `studentConcessions` collection.
 *
 *  In Phase C this reader is exercised ONLY by the read-only A/B shadow
 *  comparison inside Fee_generation_service. Production billing still reads
 *  legacy. Nothing here can write, and nothing here can change a demand.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  SCHEMA DIFFERENCES vs Fee_concession_reader (deliberate, not accidental)
 * ─────────────────────────────────────────────────────────────────────────
 *  legacy studentConcessions        →  studentEntitlements
 *    type:   percent|fixed|fullExempt →  valueType: (same vocabulary)
 *    scope:  'head'|'category'|'all'  →  scope: 'all'|'category:<c>'|'head:<id>'
 *      + targetFeeHeadId/targetCategory   (target folded INTO the scope string)
 *    (none)                           →  kind: service|concession|credit_note
 *
 *  `kind` is filtered SERVER-side: a student may legitimately hold service and
 *  credit_note entitlements in the same collection from Phase D onward, and
 *  those must never be read as concessions. This keeps the query equality-only
 *  (schoolId, studentId, status, kind), which Firestore serves by merging
 *  single-field indexes — no composite index required. See the note on the
 *  surviving studentEntitlements index in firestore.indexes.json.
 */
class Fee_entitlement_reader
{
    /** @var Firebase|null */
    private $firebase;

    /**
     * Invariant I3 (baseline §0C): a concession scoped 'all' NEVER nets against
     * a SERVICE fee head (transport / hostel / meals). A blanket "20% off
     * everything" is a tuition concession; silently discounting the bus fare
     * with it is a revenue leak, and every mature ERP scopes service charges
     * out of blanket concessions for exactly that reason.
     *
     * INERT IN PHASE C, deliberately: service fees are generated by
     * Fee_lifecycle::createModuleFee(), which does not flow through this
     * generator at all — so no spec carrying these categories can reach
     * appliesTo() yet. It is implemented here, now, because this reader is the
     * sanctioned enforcement point and Phase D routes services through the same
     * generator; leaving it out would ship a latent revenue leak with Phase D.
     */
    private const SERVICE_CATEGORIES = ['transport', 'hostel', 'meals'];

    public function init($firebase): void
    {
        $this->firebase = $firebase;
    }

    /**
     * All ACTIVE concession-kind entitlements for (schoolId, studentId, session).
     *
     * Mirrors Fee_concession_reader::activeConcessionsForStudent's contract:
     * returns the CANDIDATE set; the per-demand decision is appliesTo().
     * session=null on the entitlement → applies to every session.
     *
     * Query is equality-only with no orderBy — served by index merging.
     */
    public function activeConcessionsForStudent(string $schoolId, string $studentId, string $session): array
    {
        if ($this->firebase === null) return [];

        $rows = [];
        try {
            $rows = $this->firebase->firestoreQuery('studentEntitlements', [
                ['schoolId',  '==', $schoolId],
                ['studentId', '==', $studentId],
                ['status',    '==', 'active'],
                ['kind',      '==', 'concession'],
            ], null, 'ASC', 200);
        } catch (\Throwable $e) {
            log_message('error', "Fee_entitlement_reader: query failed for {$studentId}: " . $e->getMessage());
            return [];
        }

        $out = [];
        foreach ($rows as $r) {
            $d = is_array($r['data'] ?? null) ? $r['data'] : [];
            $eSess = $d['session'] ?? null;
            // session=null → applies to all sessions; otherwise must match.
            if ($eSess !== null && (string) $eSess !== $session) continue;
            $out[] = $d;
        }
        return $out;
    }

    /**
     * Does this entitlement apply to the demand identified by (periodKey,
     * feeHeadId, feeHead, category)? periodKey is 'YYYY-MM'.
     *
     * Match rules, intentionally identical in SEMANTICS to
     * Fee_concession_reader::appliesTo() so the Phase C shadow diff compares
     * like with like — only the field SHAPE differs:
     *   1. Scope matches ('all', 'head:<id>', 'category:<cat>').
     *   2. Effective-window overlaps the demand's month.
     *   3. Invariant I3: scope 'all' excludes service categories.
     */
    /**
     * @param string $feeHeadRef P0: the demand's school-scoped registry
     *   identity. Optional and defaulted, so every existing caller keeps
     *   working unchanged; when supplied it is the PREFERRED match (see the
     *   resolution order in the head branch below).
     */
    public function appliesTo(array $ent, string $periodKey, string $feeHeadId, string $feeHead, string $category = '', string $feeHeadRef = ''): bool
    {
        $scope = trim((string) ($ent['scope'] ?? ''));
        if ($scope === '') return false;

        if ($scope === 'all') {
            // I3 — blanket concessions never net against a service head.
            if (in_array(strtolower(trim($category)), self::SERVICE_CATEGORIES, true)) {
                return false;
            }
        } elseif (strpos($scope, 'head:') === 0) {
            // ── P0 · HEAD IDENTITY RESOLUTION ORDER (2026-08-17) ───────────
            //
            //   1. feeHeadRef   — the school-scoped registry identity. STABLE
            //                     across rename, repricing, session rollover
            //                     and class/section, so ONE head-scoped
            //                     entitlement covers every chart the head
            //                     appears in.
            //   2. feeHeadId    — LEGACY. A per-chart-row id: live data holds
            //                     28 distinct ids for 6 logical heads, so an
            //                     entitlement bound this way covers only the
            //                     chart it was created against. Existing
            //                     `head:<feeHeadId>` records must keep working,
            //                     so this branch stays.
            //   3. head NAME    — LEGACY COMPATIBILITY ONLY, for chart heads
            //                     that never had a stable id. A rename breaks
            //                     it; that hazard is registered and is exactly
            //                     why (1) exists. NOT the authority for
            //                     anything new.
            //
            // Deliberately additive: no stored scope is rewritten, no record
            // migrated, and both formats resolve simultaneously.
            $target = substr($scope, 5);
            if ($target === '') return false;
            $matched = ($feeHeadRef !== '' && $target === $feeHeadRef)   // 1
                    || ($feeHeadId  !== '' && $target === $feeHeadId)    // 2
                    || ($feeHead    !== '' && $target === $feeHead);     // 3
            if (!$matched) return false;
        } elseif (strpos($scope, 'category:') === 0) {
            $target = substr($scope, 9);
            if ($target === '' || strcasecmp($target, $category) !== 0) return false;
        } else {
            return false;   // unrecognised scope → never applies (fail closed)
        }

        // Effective window vs the demand's month — byte-identical logic to legacy.
        if (!preg_match('/^(\d{4})-(\d{2})$/', $periodKey, $m)) return false;
        $year  = (int) $m[1];
        $month = (int) $m[2];
        $firstOfMonth = sprintf('%04d-%02d-01', $year, $month);
        $lastOfMonth  = sprintf('%04d-%02d-%02d', $year, $month, (int) date('t', strtotime($firstOfMonth)));

        $effFrom = (string) ($ent['effectiveFrom'] ?? '');
        $effTo   = $ent['effectiveTo'] ?? null;
        if ($effFrom === '') return false;
        if (strcmp($effFrom, $lastOfMonth) > 0) return false;
        if ($effTo !== null && $effTo !== '' && strcmp((string) $effTo, $firstOfMonth) < 0) return false;

        return true;
    }

    /**
     * Deduction vocabulary accessors. The entitlement schema names these
     * `valueType`/`value` where the legacy collection used `type`/`value`;
     * exposing them through accessors lets the generator run ONE deduction
     * implementation over either source instead of branching on shape.
     */
    public function deductionType(array $ent): string
    {
        return (string) ($ent['valueType'] ?? '');
    }

    public function deductionValue(array $ent): float
    {
        return (float) ($ent['value'] ?? 0);
    }

    /**
     * This reader IS the ledger-backed authority: every rule it returns is a
     * real `studentEntitlements` document with its own lifecycle, so a ledger
     * row built from it references something that genuinely exists.
     *
     * Mirrors Fee_concession_reader so the generator can ask either reader the
     * same question and never learn which one it holds — the same contract
     * discipline as deductionType()/deductionValue(), whose absence caused
     * DEC-009.
     */
    public function supportsAllocationLedger(): bool
    {
        return true;
    }

    /** The grant identity the allocation ledger records. */
    public function ledgerIdentity(array $ent): string
    {
        return trim((string) ($ent['entitlementId'] ?? ''));
    }

}
